def stamp(hours_ago=0):
    return (datetime.now() - timedelta(hours=hours_ago)).strftime("%Y-%m-%d %H:%M:%S")

def add_ticket(db, user_id, title, description, category, priority, status,
               department=None, worker_id=None, hours_to_resolve=None,
               hours_ago=0, due_hours=-24, cause="", resolution="",
               incident_id=None, duplicate_of=None):
    created = stamp(hours_ago)
    completed = resolved = None
    if hours_to_resolve is not None:
        completed = stamp(hours_ago - hours_to_resolve)
        resolved = completed
    due = stamp(hours_ago - due_hours) if due_hours is not None else None
    cur = db.execute("""
        INSERT INTO tickets(
          user_id,title,description,category,priority,department,status,
          assigned_worker_id,created_at,updated_at,due_at,completed_at,resolved_at,
          cause,resolution,incident_id,duplicate_of,classification_confidence,
          review_required,estimated_hours,estimated_completion_at
        ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
    """, (user_id,title,description,category,priority,department or category,status,
          worker_id,created,stamp(max(0,hours_ago-1)),due,completed,resolved,
          cause,resolution,incident_id,duplicate_of,0.91,0,
          hours_to_resolve or 24, stamp(max(0,hours_ago-24))))
    tid=cur.lastrowid
    db.execute("INSERT INTO ticket_updates(ticket_id,actor_id,status,note,created_at) VALUES(?,?,?,?,?)",
               (tid,worker_id,status,"Demo history entry",created))
    return tid

